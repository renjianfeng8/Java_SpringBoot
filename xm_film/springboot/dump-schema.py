"""Dump the live MySQL schema (read-only) into the repo.

Usage:
    python dump-schema.py                       # 把开发库 xm-film 的结构写进 src/test/resources/db/
    python dump-schema.py --target xm_film_test # 用开发库的结构初始化/重建一个空结构库（测试库）

只执行 SELECT（information_schema）与 SHOW CREATE TABLE，不写任何数据行。
连接参数取自 application.yml 的字面量（本仓既定政策：配置直写，不经环境变量）。
"""
import argparse
import os
import subprocess
import sys

MYSQL = os.environ.get("MYSQL_EXE", "mysql")
USER = os.environ.get("MYSQL_USER", "root")
PWD = os.environ.get("MYSQL_PASSWORD", "123456")
SOURCE_DB = "xm-film"
HERE = os.path.dirname(os.path.realpath(__file__))  # .../xm_film/springboot
OUT = os.path.join(HERE, "src", "test", "resources", "db")

MYSQL_ARGS = [MYSQL, "--no-defaults", f"-u{USER}", f"-p{PWD}",
              "--default-character-set=utf8mb4", "-N", "-B", "--skip-column-names", "--raw"]


def run(sql: str) -> str:
    p = subprocess.run(MYSQL_ARGS + ["-e", sql], capture_output=True)
    if p.returncode != 0:
        sys.stderr.write(p.stderr.decode("utf-8", "replace"))
        raise SystemExit(f"mysql failed ({p.returncode})")
    return p.stdout.decode("utf-8", "replace")


def run_stdin(sql: str, db: str) -> None:
    p = subprocess.run(MYSQL_ARGS[:-2] + [db], input=sql.encode("utf-8"), capture_output=True)
    if p.returncode != 0:
        sys.stderr.write(p.stderr.decode("utf-8", "replace"))
        raise SystemExit(f"mysql failed ({p.returncode})")


def tables_of(db: str) -> list:
    raw = run(f"SELECT TABLE_NAME FROM information_schema.TABLES "
              f"WHERE TABLE_SCHEMA='{db}' ORDER BY TABLE_NAME")
    return [t for t in raw.splitlines() if t.strip()]


def create_statements(db: str) -> list:
    """按外键依赖顺序返回 (表名, DDL)。被引用的表先建，避免 ERROR 1824。"""
    tables = tables_of(db)
    fks = run("SELECT CONCAT(TABLE_NAME,'|',REFERENCED_TABLE_NAME) FROM information_schema.KEY_COLUMN_USAGE "
              f"WHERE TABLE_SCHEMA='{db}' AND REFERENCED_TABLE_NAME IS NOT NULL")
    deps = {}
    for line in fks.splitlines():
        if "|" in line:
            child, parent = line.split("|")
            deps.setdefault(child, set()).add(parent)

    ordered, seen = [], set()

    def visit(t, stack=()):
        if t in seen or t in stack:
            return
        for parent in deps.get(t, ()):
            visit(parent, stack + (t,))
        seen.add(t)
        ordered.append(t)

    for t in tables:
        visit(t)

    out = []
    for t in ordered:
        raw = run(f"SHOW CREATE TABLE `{db}`.`{t}`").strip()
        # -B 批处理模式把 DDL 内的真实换行转义成字面量 "\n"
        ddl = raw.split("\t", 1)[1] if "\t" in raw else raw
        out.append((t, ddl.replace("\\n", "\n")))
    return out


def init_empty_db(db: str) -> None:
    if db == SOURCE_DB:
        raise SystemExit("拒绝用本脚本重建开发库")
    run(f"DROP DATABASE IF EXISTS `{db}`")
    run(f"CREATE DATABASE `{db}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci")
    body = "\n".join(ddl.rstrip(";\n") + ";" for _, ddl in create_statements(SOURCE_DB))
    run_stdin(body, db)
    print(f"initialised empty schema in `{db}`: {len(tables_of(db))} tables")


def write_repo_files() -> None:
    os.makedirs(OUT, exist_ok=True)
    parts = [f"-- xm-film schema snapshot (read-only). Source DB: {SOURCE_DB}",
             "-- Generated by dump-schema.py; do not hand-edit."]
    for t, ddl in create_statements(SOURCE_DB):
        parts += ["", f"DROP TABLE IF EXISTS `{t}`;", ddl.rstrip(";\n") + ";"]
    with open(os.path.join(OUT, "schema.sql"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts) + "\n")

    inv = run(f"""
SELECT 'COL', TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_KEY, IFNULL(COLUMN_DEFAULT,'<null>'), EXTRA
  FROM information_schema.COLUMNS WHERE TABLE_SCHEMA='{SOURCE_DB}'
UNION ALL
SELECT 'IDX', TABLE_NAME, INDEX_NAME, CONCAT('non_unique=', NON_UNIQUE), COLUMN_NAME, SEQ_IN_INDEX, '', ''
  FROM information_schema.STATISTICS WHERE TABLE_SCHEMA='{SOURCE_DB}'
UNION ALL
SELECT 'TBL', TABLE_NAME, CAST(TABLE_ROWS AS CHAR), ENGINE, TABLE_COLLATION, '', IFNULL(TABLE_COMMENT,''), ''
  FROM information_schema.TABLES WHERE TABLE_SCHEMA='{SOURCE_DB}'
""").replace("\r\n", "\n")
    with open(os.path.join(OUT, "inventory.tsv"), "w", encoding="utf-8", newline="\n") as f:
        f.write(inv)
    print(f"schema.sql + inventory.tsv written to {OUT}")


def main() -> None:
    ap = argparse.ArgumentParser(description="Dump / initialise the xm-film schema")
    ap.add_argument("--target", metavar="DB",
                    help="init an empty DB with this name from the dev schema (never the dev DB itself)")
    args = ap.parse_args()
    if args.target:
        init_empty_db(args.target)
    else:
        write_repo_files()


if __name__ == "__main__":
    main()
